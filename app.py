def decide_group_request(chat_id,req_id,decision):
    group=group_owner(chat_id)
    if not group or not group_permission(chat_id,session['uid'],'requests'):return error('参加申請の管理権限がないよ',403)
    if decision not in ('approve','reject'):return error('操作が正しくないよ')
