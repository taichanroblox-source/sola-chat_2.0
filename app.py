ALLOWED_FILE_TYPES={'.pdf':'application/pdf','.txt':'text/plain','.csv':'text/csv','.md':'text/markdown','.docx':'application/vnd.openxmlformats-officedocument.wordprocessingml.document','.xlsx':'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet','.pptx':'application/vnd.openxmlformats-officedocument.presentationml.presentation'}


@app.post('/api/chats/<int:chat_id>/files')
@login_required
def send_chat_file(chat_id):
    if not membership(chat_id,session['uid']):return error('参加していないチャットだよ',403)
    if dm_blocked(chat_id):return error('ブロック中の相手には送信できないよ',403)
    f=request.files.get('file')
    if not f:return error('ファイルを選んでね')
    filename=str(f.filename or '').replace('\\','/').split('/')[-1].strip()
    filename=''.join(ch for ch in filename if ord(ch)>=32 and ch not in '<>:"|?*')[:150]
    # No executable/script formats, and never trust a supplied path.
    ext=Path(filename).suffix.lower()
    if ext not in ALLOWED_FILE_TYPES:return error('PDF・TXT・CSV・MD・DOCX・XLSX・PPTXに対応しているよ')
    raw=f.read(2*1024*1024+1)
    if not raw or len(raw)>2*1024*1024:return error('ファイルは2MB以下にしてね')
    if ext=='.pdf' and not raw.startswith(b'%PDF-'):return error('PDFファイルを確認してね')
    if ext in ('.docx','.xlsx','.pptx') and not raw.startswith(b'PK'):return error('Officeファイルを確認してね')
    if not filename:return error('ファイル名を確認してね')
    mid=insert_message(chat_id,session['uid'],'',None)
    run('INSERT INTO sola2_files (message_id,filename,mime,data) VALUES (%s,%s,%s,%s)',(mid,filename[:150],ALLOWED_FILE_TYPES[ext],raw))
    for member in rows('SELECT user_id FROM sola2_members WHERE chat_id=%s AND user_id<>%s',(chat_id,session['uid'])):
        if one('SELECT kind FROM sola2_chats WHERE id=%s',(chat_id,))['kind']=='dm' and not is_blocked(session['uid'],member['user_id']):notify(member['user_id'],'message',current_user()['username']+'がファイルを送ったよ',session['uid'],chat_id)
    return jsonify(ok=True,id=mid),201


