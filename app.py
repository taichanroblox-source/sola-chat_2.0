@app.post('/api/avatar')
@login_required
def upload_avatar():
    file = request.files.get('avatar')
    if not file:
        return error('画像を選んでね')
    raw = file.read(2 * 1024 * 1024 + 1)
    if not raw or len(raw) > 2 * 1024 * 1024:
        return error('画像は2MB以下にしてね')
    try:
        with Image.open(BytesIO(raw)) as image:
            if image.format not in ('JPEG', 'PNG', 'WEBP'):
                return error('JPEG・PNG・WebP画像を選んでね')
            if image.width * image.height > 20_000_000:
                return error('画像のサイズが大きすぎるよ')
            image = ImageOps.exif_transpose(image)
            image = ImageOps.fit(image.convert('RGB'), (256, 256), method=Image.Resampling.LANCZOS)
            out = BytesIO()
            image.save(out, format='JPEG', quality=84, optimize=True)
            binary = out.getvalue()
    except (UnidentifiedImageError, OSError, ValueError, Image.DecompressionBombError):
        return error('読み込めない画像だよ')
    existing = one('SELECT user_id FROM sola2_avatars WHERE user_id=%s', (session['uid'],))
    if existing:
        run('UPDATE sola2_avatars SET image_data=%s, updated_at=CURRENT_TIMESTAMP WHERE user_id=%s', (binary, session['uid']))
    else:
        run('INSERT INTO sola2_avatars (user_id,image_data) VALUES (%s,%s)', (session['uid'], binary))
    return jsonify(ok=True)


