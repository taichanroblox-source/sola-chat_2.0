def db():
    if 'db' not in g:
        if IS_PG:
            if psycopg is None:
                raise RuntimeError('Install psycopg[binary]')
            g.db = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        else:
            g.db = sqlite3.connect(BASE / 'sola2_local.db')
            g.db.row_factory = sqlite3.Row
            g.db.execute('PRAGMA foreign_keys = ON')
    return g.db


def run(sql, args=()):
    if not IS_PG:
        sql = sql.replace('%s', '?')
    return db().execute(sql, args)


def rows(sql, args=()):
    return [dict(x) for x in run(sql, args).fetchall()]


def one(sql, args=()):
    result = run(sql, args).fetchone()
    return dict(result) if result else None


@app.teardown_appcontext
def close_db(exc):
    conn = g.pop('db', None)
    if conn:
        if exc:
            conn.rollback()
        else:
            conn.commit()
        conn.close()


