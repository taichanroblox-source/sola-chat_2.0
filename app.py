def public_online(user):
    return bool(not user.get('hide_online') and online_value(user))


def public_status(user):
    if user.get('hide_online') or user.get('online_mode')=='invisible':return 'offline'
    if user.get('online_mode')=='busy':return 'busy'
    return 'online' if online_value(user) else 'offline'


def group_owner(chat_id):
    return one("SELECT id,name,description,announcement,creator_id,official,group_code,created_at,max_members FROM sola2_chats WHERE id=%s AND kind='group'",(chat_id,))


def online_value(user):
    from datetime import datetime, timezone
    stamp=user.get('last_seen')
    if user.get('hide_online') or user.get('online_mode') in ('invisible','busy'):return False
    if not stamp:return False
    try:
        dt=datetime.fromisoformat(str(stamp).replace('Z','+00:00'))
        if dt.tzinfo is None:dt=dt.replace(tzinfo=timezone.utc)
        # SOLA_SPEED_PRESENCE_V1: strict 40-second online window (12-second heartbeat).
        age=(datetime.now(timezone.utc)-dt).total_seconds()
        return -5 <= age < 40
    except (TypeError,ValueError):return False


