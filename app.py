@app.post('/api/register')
def register():
    data = payload()
    name = str(data.get('username','')).strip()
    password = str(data.get('password',''))
    if not re.fullmatch(r'[\w\-]{3,24}', name, re.UNICODE):
        return error('名前は3〜24文字（文字・数字・_・-）にしてね')
    if len(password) < 6 or len(password) > 128:
        return error('パスワードは6〜128文字にしてね')
    if one('SELECT id FROM sola2_users WHERE lower(username)=lower(%s)', (name,)):
        return error('その名前は使われているよ', 409)
    try:
        run('INSERT INTO sola2_users (username,password_hash,public_code) VALUES (%s,%s,%s)', (name,generate_password_hash(password),new_public_code()))
        db().commit()
    except Exception:
        db().rollback()
        return error('登録できなかったよ。別の名前で試してね', 409)
    user = one('SELECT id,username,bio,public_code FROM sola2_users WHERE username=%s', (name,))
    session.clear()
    session.permanent = True
    session['uid'] = user['id']
    session['csrf'] = secrets.token_urlsafe(32)
    return jsonify(user=current_user(),csrf=session['csrf'],official_admin=False), 201


