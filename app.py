@app.get('/api/chats/<int:chat_id>/messages')
@login_required
def messages(chat_id):
    if not membership(chat_id,session['uid']):
        return error('このチャットには参加していないよ',403)
    chat=one('SELECT id,kind,name,official,creator_id FROM sola2_chats WHERE id=%s',(chat_id,))
    if not chat:
        return error('見つからないよ',404)
    before=request.args.get('before','',type=str)
    try:before_id=int(before) if before else None
    except ValueError:return error('ページ指定が正しくないよ')
    if before_id is not None and before_id<1:return error('ページ指定が正しくないよ')
    data=rows('''SELECT m.id,m.body,m.created_at,m.edited_at,m.deleted_at,m.user_id,u.username,m.reply_to,m.is_system,
        r.body AS reply_body,ru.username AS reply_username,
        CASE WHEN im.message_id IS NULL THEN 0 ELSE 1 END AS has_image,
        f.filename AS file_name
        FROM sola2_messages m JOIN sola2_users u ON u.id=m.user_id
        LEFT JOIN sola2_messages r ON r.id=m.reply_to
        LEFT JOIN sola2_users ru ON ru.id=r.user_id
        LEFT JOIN sola2_message_images im ON im.message_id=m.id
        LEFT JOIN sola2_files f ON f.message_id=m.id
        WHERE m.chat_id=%s AND (%s IS NULL OR m.id<%s) ORDER BY m.id DESC LIMIT 60''',(chat_id,before_id,before_id))
    data.reverse()
    if data:
        ids=[m['id'] for m in data]
        placeholders=','.join(['%s']*len(ids))
        reaction_rows=rows(f'SELECT message_id,emoji,COUNT(*) AS total FROM sola2_reactions WHERE message_id IN ({placeholders}) GROUP BY message_id,emoji',tuple(ids))
        my_rows=rows(f'SELECT message_id,emoji FROM sola2_reactions WHERE user_id=%s AND message_id IN ({placeholders})',(session['uid'],*ids))
        mine={(x['message_id'],x['emoji']) for x in my_rows}
        # SOLA_SPEED_PRESENCE_V1: group reactions once instead of scanning all reactions per message.
        reaction_map={}
        for r in reaction_rows:
            reaction_map.setdefault(r['message_id'],[]).append({
                'emoji':r['emoji'],'count':r['total'],
                'mine':(r['message_id'],r['emoji']) in mine
            })
        for m in data:
            m['reactions']=reaction_map.get(m['id'],[])
    if chat['kind']=='group':
        info=group_owner(chat_id)
        chat['announcement']=info['announcement']
    # DM only: expose the other participant's last acknowledged message ID.
    # Never expose read state for unrelated chats or group participants.
    peer_read_id = 0
    if chat['kind'] == 'dm':
        peer = one('''SELECT r.last_read_id FROM sola2_chat_reads r
            JOIN sola2_members m ON m.chat_id=r.chat_id AND m.user_id=r.user_id
            WHERE r.chat_id=%s AND r.user_id<>%s
            ORDER BY r.last_read_id DESC LIMIT 1''',(chat_id,session['uid']))
        if peer:
            peer_read_id = int(peer['last_read_id'] or 0)
    group_reads = {}
    if chat['kind'] == 'group' and data:
        # Only current members; the sender does not count as a reader.
        current = rows('''SELECT m.user_id, COALESCE(r.last_read_id,0) AS last_read_id
            FROM sola2_members m LEFT JOIN sola2_chat_reads r
              ON r.chat_id=m.chat_id AND r.user_id=m.user_id
            WHERE m.chat_id=%s''',(chat_id,))
        for item in data:
            if item['user_id'] == session['uid'] and not item['is_system']:
                group_reads[str(item['id'])] = sum(
                    1 for member in current if member['user_id'] != session['uid']
                    and int(member['last_read_id'] or 0) >= int(item['id']))
    return jsonify(chat=chat,messages=data,peer_read_id=peer_read_id,group_reads=group_reads)


