def new_group_code():
    for _ in range(100):
        code=''.join(secrets.choice(GROUP_CODE_ALPHABET) for _ in range(8))
        if not one('SELECT id FROM sola2_chats WHERE group_code=%s',(code,)):
            return code
    raise RuntimeError('グループIDを作れなかったよ')


